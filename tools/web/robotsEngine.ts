/**
 * Generate standard RFC 9309 robots.txt file content
 */
export function generateRobotsTxt(config: RobotsConfig): string {
  const lines: string[] = [];

  lines.push('# ========================================================');
  lines.push('# Robots.txt Generated by ToolVerse (https://toolverse.app)');
  lines.push('# Compliant with RFC 9309 Robots Exclusion Protocol');
  lines.push('# ========================================================');
  lines.push('');

  for (const group of config.ruleGroups) {
    if (group.name) {
      lines.push(`# --- ${group.name} ---`);
    }

    const agents = group.userAgents && group.userAgents.length > 0 ? group.userAgents : ['*'];
    for (const agent of agents) {
      lines.push(`User-agent: ${agent.trim() || '*'}`);
    }

    // Allows first or Disallows
    if (group.allows && group.allows.length > 0) {
      for (const allow of group.allows) {
        const clean = allow.trim();
        if (clean) lines.push(`Allow: ${clean.startsWith('/') || clean.startsWith('*') ? clean : '/' + clean}`);
      }
    }

    if (group.disallows && group.disallows.length > 0) {
      for (const disallow of group.disallows) {
        const clean = disallow.trim();
        if (clean === '') {
          lines.push(`Disallow:`);
        } else {
          lines.push(`Disallow: ${clean.startsWith('/') || clean.startsWith('*') ? clean : '/' + clean}`);
        }
      }
    } else {
      // If group has no disallows and no allows, default empty Disallow: (allows all)
      if (!group.allows || group.allows.length === 0) {
        lines.push(`Disallow:`);
      }
    }

    if (group.crawlDelay && group.crawlDelay > 0) {
      lines.push(`Crawl-delay: ${group.crawlDelay}`);
    }

    lines.push('');
  }

  // Host directive
  if (config.host && config.host.trim()) {
    lines.push(`Host: ${config.host.trim()}`);
    lines.push('');
  }

  // Sitemaps
  if (config.sitemaps && config.sitemaps.length > 0) {
    lines.push('# Sitemaps');
    for (const sitemap of config.sitemaps) {
      const clean = sitemap.trim();
      if (clean) {
        lines.push(`Sitemap: ${clean}`);
      }
    }
  }

  return lines.join('\n').trim() + '\n';
}

/**
 * Test a URL path against current robots.txt rules according to RFC 9309 longest-match logic
 */
export function testPathAgainstRobots(
  rawPath: string,
  userAgent: string,
  config: RobotsConfig
): PathTestResult {
  let targetPath = rawPath.trim();
  if (!targetPath) targetPath = '/';
  if (!targetPath.startsWith('/')) {
    try {
      const u = new URL(targetPath);
      targetPath = u.pathname + u.search;
    } catch {
      targetPath = '/' + targetPath;
    }
  }

  const cleanAgent = userAgent.trim().toLowerCase();

  // Find most specific rule group matching userAgent
  let matchedGroup: RobotsRuleGroup | null = null;
  let isSpecificMatch = false;

  for (const group of config.ruleGroups) {
    const agents = (group.userAgents || []).map((a) => a.trim().toLowerCase());
    if (agents.includes(cleanAgent)) {
      matchedGroup = group;
      isSpecificMatch = true;
      break;
    }
  }

  // Fallback to wildcard '*'
  if (!matchedGroup) {
    for (const group of config.ruleGroups) {
      const agents = (group.userAgents || []).map((a) => a.trim().toLowerCase());
      if (agents.includes('*')) {
        matchedGroup = group;
        break;
      }
    }
  }

  if (!matchedGroup) {
    return {
      path: targetPath,
      userAgent,
      isAllowed: true,
      matchedDirective: 'Default',
      reason: 'No matching User-agent rule block found in configuration. Access is allowed by default.',
    };
  }

  // Compare matches: RFC 9309 specifies the longest matching pattern takes precedence.
  // If equal length, Allow takes precedence over Disallow.
  let bestMatchLength = -1;
  let bestDirective: 'Allow' | 'Disallow' | null = null;
  let bestPattern = '';

  const testMatch = (pattern: string, directive: 'Allow' | 'Disallow') => {
    let p = pattern.trim();
    if (!p) return;
    if (!p.startsWith('/') && !p.startsWith('*')) p = '/' + p;

    // Convert robots wildcard syntax (* and $) to regex
    const regexStr = '^' + p
      .replace(/[.+?^${}()|[\]\\]/g, '\\$&') // escape special regex except * and $
      .replace(/\*/g, '.*')
      .replace(/\\\$$/, '$'); // keep $ at end if specified

    try {
      const re = new RegExp(regexStr);
      if (re.test(targetPath) || targetPath.startsWith(p.replace(/\*.*$/, ''))) {
        const patternLen = p.length;
        if (patternLen > bestMatchLength) {
          bestMatchLength = patternLen;
          bestDirective = directive;
          bestPattern = p;
        } else if (patternLen === bestMatchLength && directive === 'Allow') {
          // Allow wins tie-break
          bestDirective = 'Allow';
          bestPattern = p;
        }
      }
    } catch {
      // Fallback simple prefix check
      if (targetPath.startsWith(p)) {
        if (p.length > bestMatchLength) {
          bestMatchLength = p.length;
          bestDirective = directive;
          bestPattern = p;
        }
      }
    }
  };

  // Evaluate Allows
  for (const allow of matchedGroup.allows || []) {
    testMatch(allow, 'Allow');
  }

  // Evaluate Disallows
  for (const disallow of matchedGroup.disallows || []) {
    testMatch(disallow, 'Disallow');
  }

  if (bestDirective === 'Disallow') {
    return {
      path: targetPath,
      userAgent,
      isAllowed: false,
      matchedRuleGroup: matchedGroup.name || (isSpecificMatch ? userAgent : '*'),
      matchedDirective: 'Disallow',
      matchedPattern: bestPattern,
      reason: `Blocked by Disallow: ${bestPattern} under User-agent: ${isSpecificMatch ? userAgent : '*'}`,
    };
  } else if (bestDirective === 'Allow') {
    return {
      path: targetPath,
      userAgent,
      isAllowed: true,
      matchedRuleGroup: matchedGroup.name || (isSpecificMatch ? userAgent : '*'),
      matchedDirective: 'Allow',
      matchedPattern: bestPattern,
      reason: `Permitted by Allow: ${bestPattern} under User-agent: ${isSpecificMatch ? userAgent : '*'}`,
    };
  }

  return {
    path: targetPath,
    userAgent,
    isAllowed: true,
    matchedRuleGroup: matchedGroup.name || (isSpecificMatch ? userAgent : '*'),
    matchedDirective: 'Default',
    reason: `No matching Allow or Disallow patterns matched this path. Access is allowed by default.`,
  };
}

/**
 * Audit robots.txt configuration for common SEO mistakes
 */
export function validateRobotsConfig(config: RobotsConfig): RobotsValidationReport {
  const issues: RobotsValidationIssue[] = [];
  let hasTotalBlock = false;

  // 1. Check for total site blocking under wildcard
  for (const group of config.ruleGroups) {
    const isWildcard = (group.userAgents || []).includes('*');
    if (isWildcard) {
      if ((group.disallows || []).includes('/')) {
        const hasAllow = (group.allows || []).some((a) => a === '/' || a === '/*');
        if (!hasAllow) {
          hasTotalBlock = true;
          issues.push({
            type: 'error',
            message: 'Total Site Crawling Blocked: Disallow: / under User-agent: *',
            recommendation:
              'This completely blocks search engines like Google and Bing from crawling and indexing your website. Remove Disallow: / unless this is a private staging server.',
          });
        }
      }
    }
  }

  // 2. Validate Sitemaps
  if (!config.sitemaps || config.sitemaps.length === 0) {
    issues.push({
      type: 'warning',
      message: 'No Sitemap directive specified',
      recommendation:
        'Adding a Sitemap: https://yourdomain.com/sitemap.xml line helps search crawlers quickly discover all your pages and fresh content.',
    });
  } else {
    for (const sm of config.sitemaps) {
      if (!sm.startsWith('http://') && !sm.startsWith('https://')) {
        issues.push({
          type: 'error',
          message: `Invalid Sitemap URL: "${sm}"`,
          recommendation: 'Sitemap directives must be fully-qualified absolute URLs starting with https://.',
        });
      }
    }
  }

  // 3. Validate Disallow & Allow format
  for (const group of config.ruleGroups) {
    for (const d of group.disallows || []) {
      const clean = d.trim();
      if (clean && !clean.startsWith('/') && !clean.startsWith('*')) {
        issues.push({
          type: 'warning',
          message: `Path missing leading slash: "Disallow: ${clean}"`,
          recommendation: `Change to "Disallow: /${clean}". Robots paths should begin with a forward slash.`,
        });
      }
    }
    for (const a of group.allows || []) {
      const clean = a.trim();
      if (clean && !clean.startsWith('/') && !clean.startsWith('*')) {
        issues.push({
          type: 'warning',
          message: `Path missing leading slash: "Allow: ${clean}"`,
          recommendation: `Change to "Allow: /${clean}". Robots paths should begin with a forward slash.`,
        });
      }
    }
  }

  const isValid = issues.filter((i) => i.type === 'error').length === 0;

  return {
    isValid,
    hasTotalBlock,
    sitemapCount: (config.sitemaps || []).length,
    ruleGroupCount: (config.ruleGroups || []).length,
    issues,
  };
}

