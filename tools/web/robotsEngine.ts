/**
 * ToolVerse Robots.txt Engine
 * Implements RFC 9309 (Robots Exclusion Protocol), rule generation, multi-bot grouping, path matching, and validation.
 * Pure TypeScript with zero external dependencies.
 */

export interface RobotsRuleGroup {
  id: string;
  name?: string;
  userAgents: string[];
  allows: string[];
  disallows: string[];
  crawlDelay?: number;
}

export interface RobotsConfig {
  ruleGroups: RobotsRuleGroup[];
  sitemaps: string[];
  host?: string;
}

export interface PathTestResult {
  path: string;
  userAgent: string;
  isAllowed: boolean;
  matchedRuleGroup?: string;
  matchedDirective?: 'Allow' | 'Disallow' | 'Default';
  matchedPattern?: string;
  reason: string;
}

export interface RobotsValidationIssue {
  type: 'error' | 'warning' | 'info';
  message: string;
  recommendation: string;
}

export interface RobotsValidationReport {
  isValid: boolean;
  hasTotalBlock: boolean;
  sitemapCount: number;
  ruleGroupCount: number;
  issues: RobotsValidationIssue[];
}

